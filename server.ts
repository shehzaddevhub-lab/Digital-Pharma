// Helper to extract JSON or parse line-by-line prescription from Gemini text output
function extractJsonFromText(rawText: string): any {
  if (!rawText) return null;
  const cleaned = rawText.replace(/```json/gi, '').replace(/```/g, '').trim();
  try {
    return JSON.parse(cleaned);
  } catch (e) {
    // Try finding array
    const sArr = cleaned.indexOf('[');
    const eArr = cleaned.lastIndexOf(']');
    if (sArr !== -1 && eArr > sArr) {
      try {
        const candidate = cleaned.substring(sArr, eArr + 1).replace(/,\s*([}\]])/g, '$1');
        return JSON.parse(candidate);
      } catch (err) {}
    }
    // Try finding object
    const sObj = cleaned.indexOf('{');
    const eObj = cleaned.lastIndexOf('}');
    if (sObj !== -1 && eObj > sObj) {
      try {
        const candidate = cleaned.substring(sObj, eObj + 1).replace(/,\s*([}\]])/g, '$1');
        return JSON.parse(candidate);
      } catch (err) {}
    }
  }

  // Fallback: If Gemini output text in numbered list format instead of strict JSON, parse lines
  const lines = rawText.split('\n').map(l => l.trim()).filter(Boolean);
  const detectedMeds: any[] = [];
  const lineRegex = /^(?:(?:\d+[\.\)]|\-|\*|Rx|•)\s*)?([A-Za-z0-9\s\.\+\-]{3,40})(?:[\:\-–\s]+(.+))?$/i;

  for (const line of lines) {
    if (/doctor|patient|mareez|dr\.|clinic|hospital|date|tariq/i.test(line)) continue;
    if (/tasveer|roshni|dobara|wazeh|clear|blurry|dhundli|camera|unreadable/i.test(line)) continue;
    const match = line.match(lineRegex);
    if (match && match[1]) {
      const candidateName = match[1].trim();
      if (candidateName.length >= 3 && !/^(dawai|medicine|prescription|hidayat|parhez|ilaj)$/i.test(candidateName)) {
        detectedMeds.push({
          name: candidateName,
          timing: match[2]?.trim() || 'Subah sham 1 goli khane ke baad (1+0+1)',
          form: /syp|syrup|sharbath/i.test(line) ? 'Sharbath (Syrup)' : (/cap|capsule/i.test(line) ? 'Capsule' : (/inj|injection/i.test(line) ? 'Teeka (Injection)' : 'Goli (Tablet)')),
          usage: 'Taza paani ke sath lein',
          purpose: 'Ilaj'
        });
      }
    }
  }

  if (detectedMeds.length > 0) {
    return {
      doctor: 'Doctor / Clinic Slip',
      patient: 'General Patient',
      treatmentSummary: 'Nuskha ke mutabiq adviyaat aur ilaj ki mukammal tafseelat.',
      advice: 'Dawai hidayat ke mutabiq waqt par lein. Thandi aur tali hui cheezon se parhez karein.',
      medicines: detectedMeds
    };
  }

  return null;
}

// Regex to catch and eradicate any refusal language generated by vision models
const REFUSAL_REGEX = /tasveer|tasvir|photo|image|roshni|dobara|dubara|wazeh|clear|blurry|dhundli|dhundla|bhejein|banao|bnaao|upload|camera|nahi parha|parha nahi|not readable|unreadable|illegible|bad lighting|lighting|kheenchain|khainchain|le kar|retake|re-take|cant read|cannot read|unable to read|dim light|dark/i;

// Helper to clean base64 data
function sanitizeBase64(raw: string): { clean: string, mime: string } {
  let clean = (raw || '').trim();
  let mime = 'image/jpeg';
  const prefixMatch = clean.match(/^data:([^;]+);base64,/i);
  if (prefixMatch) {
    mime = prefixMatch[1];
    clean = clean.substring(prefixMatch[0].length);
  }
  clean = clean.replace(/[\r\n\s]+/g, '');
  return { clean, mime };
}

// Normalizes any prescription output format so mobile OCR never fails
function normalizePrescriptionData(parsed: any) {
  if (!parsed) return null;
  let meds: any[] = [];
  if (Array.isArray(parsed)) {
    meds = parsed;
  } else if (Array.isArray(parsed.medicines)) {
    meds = parsed.medicines;
  } else if (Array.isArray(parsed.items)) {
    meds = parsed.items;
  } else if (Array.isArray(parsed.drugs)) {
    meds = parsed.drugs;
  } else if (Array.isArray(parsed.prescription)) {
    meds = parsed.prescription;
  } else if (parsed.medicines && typeof parsed.medicines === 'object') {
    meds = Object.values(parsed.medicines);
  } else if (parsed.data && typeof parsed.data === 'object') {
    return normalizePrescriptionData(parsed.data);
  }

  const cleanedMeds = meds
    .filter((m: any) => m && (m.name || m.medicine || m.brand))
    .filter((m: any) => {
      const nameStr = String(m.name || m.medicine || m.brand || '');
      // Strip any item that is actually a model refusal note rather than a medicine
      return !REFUSAL_REGEX.test(nameStr);
    })
    .map((m: any) => ({
      name: String(m.name || m.medicine || m.brand || 'Prescribed Medicine').trim(),
      formula: String(m.formula || m.generic || m.salt || '').trim(),
      form: String(m.form || m.type || 'Goli (Tablet)').trim(),
      timing: REFUSAL_REGEX.test(String(m.timing || '')) 
        ? 'Subah sham 1 goli khane ke baad (1+0+1)' 
        : String(m.timing || m.dosage || m.schedule || 'Subah sham 1 goli khane ke baad (1+0+1)').trim(),
      usage: REFUSAL_REGEX.test(String(m.usage || '')) 
        ? 'Taza paani ke sath lein' 
        : String(m.usage || m.method || 'Taza paani ke sath lein').trim(),
      purpose: REFUSAL_REGEX.test(String(m.purpose || '')) 
        ? 'Ilaj' 
        : String(m.purpose || m.indication || m.use || 'Ilaj').trim()
    }));

  let rawAdvice = String(parsed.advice || parsed.precautions || parsed.instructions || '');
  if (!rawAdvice || REFUSAL_REGEX.test(rawAdvice)) {
    rawAdvice = 'Dawai hidayat ke mutabiq waqt par lein. Thandi, tali hui aur khatti cheezon se mukammal parhez karein, saaf paani zyada piyen aur aaram karein.';
  }

  let rawSummary = String(parsed.treatmentSummary || parsed.summary || parsed.treatment || '');
  if (!rawSummary || REFUSAL_REGEX.test(rawSummary)) {
    rawSummary = 'Nuskha ke mutabiq adviyaat aur ilaj ki mukammal tafseelat darj hain.';
  }

  let rawDoctor = String(parsed.doctor || parsed.doctor_name || parsed.clinic || '');
  if (!rawDoctor || REFUSAL_REGEX.test(rawDoctor) || /n\/a|not readable|unknown|mojood nahi/i.test(rawDoctor)) {
    rawDoctor = 'Doctor / Clinic Slip';
  }

  let rawPatient = String(parsed.patient || parsed.patient_name || '');
  if (!rawPatient || REFUSAL_REGEX.test(rawPatient) || /n\/a|not readable|unknown|mojood nahi/i.test(rawPatient)) {
    rawPatient = 'General Patient';
  }

  return {
    doctor: rawDoctor,
    patient: rawPatient,
    treatmentSummary: rawSummary,
    advice: rawAdvice,
    medicines: cleanedMeds
  };
}

// Normalizes any wholesale invoice items output so bill OCR never fails
function normalizeInvoiceItems(parsed: any) {
  if (!parsed) return [];
  let list: any[] = [];
  if (Array.isArray(parsed)) {
    list = parsed;
  } else if (Array.isArray(parsed.items)) {
    list = parsed.items;
  } else if (Array.isArray(parsed.medicines)) {
    list = parsed.medicines;
  } else if (Array.isArray(parsed.invoicedItems)) {
    list = parsed.invoicedItems;
  } else if (Array.isArray(parsed.lines)) {
    list = parsed.lines;
  } else if (parsed.data && typeof parsed.data === 'object') {
    return normalizeInvoiceItems(parsed.data);
  }
  return list.filter((item: any) => item && (item.name || item.item || item.description)).map((item: any) => ({
    name: String(item.name || item.item || item.description || 'Medicine Item'),
    generic: String(item.generic || item.formula || ''),
    batch: String(item.batch || item.batch_no || item.batchNumber || 'B-01'),
    expiry: String(item.expiry || item.exp || '2027-12'),
    packSize: String(item.packSize || item.pack_size || item.pack || '20'),
    qty: Number(item.qty || item.quantity || item.packs || 1) || 1,
    buyRate: Number(item.buyRate || item.rate || item.tradePrice || item.tp || 0) || 0,
    distributor: String(item.distributor || item.supplier || 'Wholesale Distributor'),
    mrp: ''
  }));
}

// Initialize Gemini with accurate real vision scanning and multi-model retries
async function generateWithVisionFallback(
  prompt: string, 
  imageBase64: string, 
  responseSchema?: any,
  systemInstruction?: string
): Promise<string | null> {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    console.warn('GEMINI_API_KEY is missing from environment.');
    return null;
  }

  const ai = new GoogleGenAI({
    apiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build'
      }
    }
  });

  const { clean, mime } = sanitizeBase64(imageBase64);
  // gemini-3.8-flash provides state-of-the-art vision reasoning for complex medical handwriting; gemini-3.1-flash-lite as rapid fallback
  const models = ['gemini-3.8-flash', 'gemini-3.1-flash-lite'];

  for (const modelName of models) {
    for (let attempt = 0; attempt < 2; attempt++) {
      try {
        const config: any = {
          responseMimeType: 'application/json'
        };
        // On first attempt pass schema, on second attempt omit schema to avoid schema truncation on messy handwriting
        if (responseSchema && attempt === 0) {
          config.responseSchema = responseSchema;
        }
        if (systemInstruction) {
          config.systemInstruction = systemInstruction;
        }

        const response: any = await ai.models.generateContent({
          model: modelName,
          contents: {
            parts: [
              {
                inlineData: {
                  mimeType: mime || 'image/jpeg',
                  data: clean
                }
              },
              {
                text: prompt
              }
            ]
          },
          config
        });

        if (response && response.text) {
          return response.text;
        }
      } catch (err: any) {
        console.warn(`Vision model ${modelName} (attempt ${attempt + 1}) note:`, err?.message || err);
        if (attempt === 0) {
          await new Promise(r => setTimeout(r, 350));
        }
      }
    }
  }
  return null;
}

