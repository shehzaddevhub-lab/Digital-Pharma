function normalizePrescriptionData(parsed: any) {
  if (!parsed) return null;
  let meds: any[] = [];
  let root = parsed;

  if (Array.isArray(root)) {
    if (root.length > 0 && root[0] && typeof root[0] === 'object') {
      if (Array.isArray(root[0].medicines) || Array.isArray(root[0].items) || Array.isArray(root[0].lineItems) || Array.isArray(root[0].drugs)) {
        root = root[0];
      }
    }
  }

  if (Array.isArray(root)) {
    meds = root;
  } else if (Array.isArray(root.medicines)) {
    meds = root.medicines;
  } else if (Array.isArray(root.items)) {
    meds = root.items;
  } else if (Array.isArray(root.lineItems)) {
    meds = root.lineItems;
  } else if (Array.isArray(root.drugs)) {
    meds = root.drugs;
  } else if (Array.isArray(root.prescription)) {
    meds = root.prescription;
  } else if (Array.isArray(root.prescribedMedicines)) {
    meds = root.prescribedMedicines;
  } else if (Array.isArray(root.prescriptions)) {
    meds = root.prescriptions;
  } else if (Array.isArray(root.meds)) {
    meds = root.meds;
  } else if (Array.isArray(root.list)) {
    meds = root.list;
  } else if (root.medicines && typeof root.medicines === 'object') {
    meds = Object.values(root.medicines);
  } else if (root.data && typeof root.data === 'object') {
    return normalizePrescriptionData(root.data);
  }

  const cleanedMeds = meds
    .map((m: any) => {
      if (typeof m === 'string') {
        const clean = m.trim().replace(/^[\*\-\d\.\)\s]+/, '').trim();
        if (clean.length < 2 || isModelRefusal(clean)) return null;
        const parts = clean.split(/[-–—:]/);
        const name = parts[0].trim().replace(/^[\*\#_]+|[\*\#_]+$/g, '');
        const timing = parts[1]?.trim().replace(/^[\*\#_]+|[\*\#_]+$/g, '') || 'Subah sham 1 goli khane ke baad (1+0+1)';
        const shortUse = getMedicineShortUse(name, '');
        return {
          name,
          formula: '',
          timing,
          usage: 'Taza paani ke sath lein',
          shortUse
        };
      }
      if (!m || typeof m !== 'object') return null;
      const name = String(m.name || m.medicine || m.brand || m.drug || m.item || m.medicineName || m.title || m.label || '').trim();
      if (!name || isModelRefusal(name)) return null;
      const formula = String(m.formula || m.generic || m.salt || m.composition || '').trim();
      const rawUse = String(m.shortUse || m.use || m.purpose || m.indication || m.reason || '').trim();
      const shortUseHint = rawUse || getMedicineShortUse(name, formula);
      return {
        name,
        formula,
        timing: isModelRefusal(String(m.timing || '')) 
          ? 'Subah sham 1 goli khane ke baad (1+0+1)' 
          : String(m.timing || m.dosage || m.dose || m.schedule || m.frequency || 'Subah sham 1 goli khane ke baad (1+0+1)').trim(),
        usage: isModelRefusal(String(m.usage || '')) 
          ? 'Taza paani ke sath lein' 
          : String(m.usage || m.method || 'Taza paani ke sath lein').trim(),
        shortUse: shortUseHint
      };
    })
    .filter(Boolean);

  let rawAdvice = String(root.advice || root.precautions || root.instructions || '');
  if (!rawAdvice || isModelRefusal(rawAdvice)) {
    rawAdvice = 'Dawai hidayat ke mutabiq waqt par lein. Thandi, tali hui aur khatti cheezon se parhez karein aur saaf paani zyada piyen.';
  }

  let rawSummary = String(root.treatmentSummary || root.summary || root.treatment || '');
  if (!rawSummary || isModelRefusal(rawSummary)) {
    rawSummary = 'Nuskha ke mutabiq adviyaat aur ilaj ki mukammal tafseelat darj hain.';
  }

  let rawDoctor = '';
  if (typeof root.doctor === 'string') rawDoctor = root.doctor;
  else if (root.doctor && typeof root.doctor === 'object' && root.doctor.name) rawDoctor = root.doctor.name;
  else if (root.clinic) rawDoctor = String(root.clinic);
  else if (root.doctorName) rawDoctor = String(root.doctorName);
  if (!rawDoctor || isModelRefusal(rawDoctor) || /n\/a|not readable|unknown|mojood nahi/i.test(rawDoctor)) {
    rawDoctor = 'Doctor / Clinic Slip';
  }

  let rawPatient = '';
  if (typeof root.patient === 'string') rawPatient = root.patient;
  else if (root.patient && typeof root.patient === 'object' && root.patient.name) rawPatient = root.patient.name;
  else if (root.patientName) rawPatient = String(root.patientName);
  if (!rawPatient || isModelRefusal(rawPatient) || /n\/a|not readable|unknown|mojood nahi/i.test(rawPatient)) {
    rawPatient = 'General Patient';
  }

  return {
    doctor: rawDoctor,
    patient: rawPatient,
    treatmentSummary: rawSummary,
    advice: rawAdvice,
    medicines: cleanedMeds
  };
}

// Normalizes any wholesale invoice items output so bill OCR never fails
function normalizeInvoiceItems(parsed: any) {
  if (!parsed) return { items: [], summary: null };
  let list: any[] = [];
  let root = parsed;

  if (Array.isArray(root)) {
    if (root.length > 0 && root[0] && typeof root[0] === 'object') {
      if (Array.isArray(root[0].lineItems) || Array.isArray(root[0].items) || Array.isArray(root[0].medicines) || Array.isArray(root[0].products) || Array.isArray(root[0].rows)) {
        root = root[0];
      }
    }
  }

  if (Array.isArray(root)) {
    list = root;
  } else if (Array.isArray(root.lineItems)) {
    list = root.lineItems;
  } else if (Array.isArray(root.items)) {
    list = root.items;
  } else if (Array.isArray(root.medicines)) {
    list = root.medicines;
  } else if (Array.isArray(root.invoicedItems)) {
    list = root.invoicedItems;
  } else if (Array.isArray(root.invoiceItems)) {
    list = root.invoiceItems;
  } else if (Array.isArray(root.lines)) {
    list = root.lines;
  } else if (Array.isArray(root.products)) {
    list = root.products;
  } else if (Array.isArray(root.rows)) {
    list = root.rows;
  } else if (Array.isArray(root.table)) {
    list = root.table;
  } else if (Array.isArray(root.billItems)) {
    list = root.billItems;
  } else if (root.data && typeof root.data === 'object') {
    return normalizeInvoiceItems(root.data);
  }

  const detectedDist = String(root.distributorName || root.distributor || root.supplier || root.vendor || '').trim();

  // Summary and discount extractions from bill
  const totalBillAmount = Number(root.totalBillAmount || root.netTotal || root.totalAmount || root.grandTotal || root.netPayable || root.billTotal || 0) || 0;
  const subtotalAmount = Number(root.subtotal || root.grossTotal || root.total || 0) || 0;
  const discountPercent = Number(root.discountPercent || root.discountPct || root.discPercent || root.overallDiscountPercent || root.discount || 0) || 0;
  const extraDiscountPercent = Number(root.extraDiscountPercent || root.extraDiscPercent || root.specialDiscountPercent || 0) || 0;
  const discountAmount = Number(root.discountAmount || root.discountAmt || root.discAmount || 0) || 0;

  function cleanExpiryField(rawExp: any): string {
    if (!rawExp) return '';
    const str = String(rawExp).trim();
    if (!str || /null|undefined|none|n\/a|not printed|na|nil/i.test(str)) return '';
    return str;
  }

  function detectTypeFromFullName(name: string): string {
    const n = String(name || '').toLowerCase();
    // 1. Syrups & Suspensions (syp, surup, syrup, srup, syr, susp, suspension, elixir, solution, sol)
    if (/\b(syp|syrup|surup|srup|syr|susp|suspension|elixir|solution|sol)\b/i.test(n) || /syp\.|syrup\.|surup\./i.test(n)) return 'syp';
    // 2. Capsules (cap, capsule, capsules, softgel, cap.)
    if (/\b(cap|capsule|caps|softgel)\b/i.test(n) || /cap\./i.test(n)) return 'cap';
    // 3. Drops (drop, drops, eye drop, ear drop, nasal drop)
    if (/\b(drop|drops|drp|drps)\b/i.test(n) || /drop\./i.test(n)) return 'drop';
    // 4. Injections & Infusions (inj, injection, infusion, amp, ampoule, vial, iv, im)
    if (/\b(inj|injection|infusion|inf|amp|ampoule|vial|iv|im)\b/i.test(n) || /inj\./i.test(n)) return 'inj';
    // 5. Sachets (sachet, sachets, scht, sct, powder, granules)
    if (/\b(sachet|sachets|scht|sct|powder|granules)\b/i.test(n) || /scht\./i.test(n)) return 'scht';
    // 6. Creams & Ointments (cream, oint, ointment, gel, lotion, emulgel)
    if (/\b(cream|gel|ointment|oint|lotion|emulgel)\b/i.test(n) || /oint\.|crm\./i.test(n)) return 'cream';
    // 7. Surgical & Disposables (surgical, syringe, cannula, bandage, cotton, gloves, tape)
    if (/\b(surgical|bandage|cannula|syringe|cotton|gloves|blade|tape)\b/i.test(n)) return 'surgical';
    // 8. Tablets (tab, tablet, tablets, tabs, tab.)
    if (/\b(tab|tablet|tablets|tabs)\b/i.test(n) || /tab\./i.test(n)) return 'tab';
    return 'tab';
  }

  const cleanedItems = list.filter((item: any) => item && (item.name || item.itemName || item.item || item.description || item.medicine || item.product) && !isModelRefusal(String(item.name || item.item))).map((item: any) => {
    const rawName = String(item.name || item.itemName || item.item || item.description || item.medicine || item.product || 'Medicine Item').trim();
    // Prioritize detecting type directly from complete medicine name to avoid OCR hallucinating random types
    const detectedFromFull = detectTypeFromFullName(rawName);
    const itemType = detectedFromFull || (item.type ? detectTypeFromFullName(String(item.type)) : 'tab');
    const itemDisc = Number(item.discountPercent || item.discount || item.discPct || 0) || 0;
    const itemExtraDisc = Number(item.extraDiscountPercent || item.extraDiscount || item.bonusPercent || 0) || 0;

    return {
      name: rawName,
      type: itemType,
      generic: String(item.generic || item.formula || '').trim(),
      batch: String(item.batch || item.batch_no || item.batchNo || item.batchNumber || '').trim(),
      // STRICT: ONLY use expiry if physically printed on the bill, never fabricate a future expiry
      expiry: cleanExpiryField(item.expiry || item.exp),
      packSize: String(item.packSize || item.pack_size || item.pack || '20').trim(),
      qty: Number(item.qty || item.quantity || item.packs || item.count || 1) || 1,
      buyRate: Number(item.buyRate || item.rate || item.tradePrice || item.tp || item.price || item.unitPrice || 0) || 0,
      discountPercent: itemDisc,
      extraDiscountPercent: itemExtraDisc,
      distributor: String(item.distributor || item.supplier || detectedDist || 'Wholesale Distributor').trim(),
      mrp: ''
    };
  });

  return {
    items: cleanedItems,
    summary: {
      distributorName: detectedDist,
      totalBillAmount,
      subtotalAmount,
      discountPercent,
      extraDiscountPercent,
      discountAmount
    }
  };
}

