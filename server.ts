interface NetworkPharmacy {
  id: string;
  name: string;
  ownerName?: string;
  city: string;
  phone: string;
  email?: string;
  licenseNo?: string;
  remarks?: string;
  updatedAt: string;
}

const NETWORK_FILE = path.resolve(__dirname, 'network_pharmacies.json');

function loadNetworkPharmacies(): NetworkPharmacy[] {
  try {
    if (fs.existsSync(NETWORK_FILE)) {
      const data = fs.readFileSync(NETWORK_FILE, 'utf-8');
      const parsed = JSON.parse(data);
      if (Array.isArray(parsed)) return parsed;
    }
  } catch (e) {
    console.error('Error reading network pharmacies file:', e);
  }
  return [];
}

function saveNetworkPharmacies(list: NetworkPharmacy[]) {
  try {
    fs.writeFileSync(NETWORK_FILE, JSON.stringify(list, null, 2), 'utf-8');
  } catch (e) {
    console.error('Error saving network pharmacies file:', e);
  }
}

let activeNetworkPharmacies = loadNetworkPharmacies();

app.get('/api/network/pharmacies', (_req: Request, res: Response) => {
  res.json({
    success: true,
    count: activeNetworkPharmacies.length,
    pharmacies: activeNetworkPharmacies
  });
});

app.post('/api/network/unregister', (req: Request, res: Response): void => {
  try {
    const { email, phone, name } = req.body;
    const cleanEmail = email ? String(email).trim().toLowerCase() : '';
    const cleanPhone = phone ? String(phone).replace(/\D/g, '') : '';
    const cleanName = name ? String(name).trim().toLowerCase() : '';

    activeNetworkPharmacies = activeNetworkPharmacies.filter(p => {
      if (cleanEmail && p.email && p.email.toLowerCase() === cleanEmail) return false;
      if (cleanPhone && p.phone && p.phone.replace(/\D/g, '') === cleanPhone) return false;
      if (cleanName && p.name.toLowerCase() === cleanName) return false;
      return true;
    });

    saveNetworkPharmacies(activeNetworkPharmacies);
    res.json({ success: true, count: activeNetworkPharmacies.length });
  } catch(e) {
    res.status(500).json({ success: false, error: 'Unregister failed' });
  }
});

app.post('/api/network/register', (req: Request, res: Response): void => {
  try {
    const { name, ownerName, city, phone, email, licenseNo, remarks } = req.body;
    if (!name || !city || !phone) {
      res.status(400).json({ success: false, error: 'Pharmacy Name, City aur Phone zaroori hain.' });
      return;
    }

    const cleanPhone = String(phone).trim();
    const cleanName = String(name).trim();
    const cleanCity = String(city).trim();
    const cleanEmail = email ? String(email).trim().toLowerCase() : '';

    // Check if store already registered by email, phone, or name
    const existingIndex = activeNetworkPharmacies.findIndex(p => 
      (cleanEmail && p.email && p.email.toLowerCase() === cleanEmail) ||
      (p.phone && p.phone.replace(/\D/g, '') === cleanPhone.replace(/\D/g, '')) ||
      (p.name.toLowerCase() === cleanName.toLowerCase() && p.city.toLowerCase() === cleanCity.toLowerCase())
    );

    const record: NetworkPharmacy = {
      id: existingIndex !== -1 ? activeNetworkPharmacies[existingIndex].id : ('net_' + Date.now()),
      name: cleanName,
      ownerName: (ownerName || '').trim() || (cleanEmail ? cleanEmail.split('@')[0] : 'Store Owner'),
      city: cleanCity,
      phone: cleanPhone,
      email: cleanEmail,
      licenseNo: (licenseNo || '').trim(),
      remarks: (remarks || 'Active Digital Pharma Connected Pharmacy').trim(),
      updatedAt: new Date().toISOString()
    };

    if (existingIndex !== -1) {
      activeNetworkPharmacies[existingIndex] = record;
    } else {
      activeNetworkPharmacies.unshift(record);
    }

    saveNetworkPharmacies(activeNetworkPharmacies);

    res.json({
      success: true,
      message: `${cleanName} successfully registered in Digital Pharma Network!`,
      pharmacy: record,
      totalConnected: activeNetworkPharmacies.length
    });
  } catch (err: any) {
    console.error('Network registration error:', err);
    res.status(500).json({ success: false, error: 'Network registration failed' });
  }
});

